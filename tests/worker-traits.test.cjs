const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const source=fs.readFileSync(path.join(__dirname,'../dist/client/game.js'),'utf8');
const start=source.indexOf('  const roleStats =');
const end=source.indexOf('  const statGrowth =',start);
assert(start>0&&end>start);
const context={statLabels:[['design'],['sewing'],['trend'],['efficiency']]};
vm.createContext(context);
vm.runInContext(source.slice(start,end)+'\nthis.baseStats=baseStats;',context);
const yuna=context.baseStats({id:'yuna',level:1,role:'디자인'});
const raon=context.baseStats({id:'raon',level:1,role:'디자인'});
const minho=context.baseStats({id:'minho',level:1,role:'생산'});
assert(yuna.design>raon.design);
assert(raon.trend>yuna.trend);
assert(minho.sewing>yuna.sewing);
assert.notEqual(JSON.stringify(yuna),JSON.stringify(raon));
console.log('Individual traits distinguish employees even at the same tier and role.');
