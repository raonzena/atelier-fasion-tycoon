const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');

const source=fs.readFileSync(path.join(__dirname,'../dist/client/game.js'),'utf8');
const start=source.indexOf('  const hiredWorkers =');
const end=source.indexOf('  const ownedItems =',start);
assert(start>0&&end>start);
const state={hired:['yuna','tani']};
const context={state,workers:[{id:'yuna',cost:24,ability:6},{id:'tani',cost:31,ability:10}],employeeStats:w=>({design:w.ability,sewing:w.ability,trend:w.ability,efficiency:w.ability}),roundMoney:value=>Math.round(value*10)/10};
vm.createContext(context);
vm.runInContext(source.slice(start,end)+'\nthis.payroll={hiringCost,monthlySalary,monthlyPayroll};',context);
assert.equal(context.payroll.hiringCost(context.workers[0]),12);
assert.equal(context.payroll.hiringCost(context.workers[1]),15.5);
assert.equal(context.payroll.monthlySalary(context.workers[0]),11.7);
assert.equal(context.payroll.monthlySalary(context.workers[1]),19.6);
assert.equal(context.payroll.monthlyPayroll(),31.3);
context.workers[1].ability=14;
assert.equal(context.payroll.monthlySalary(context.workers[1]),24);
assert.equal(context.payroll.monthlyPayroll(),35.7);
state.hired=['tani'];
assert.equal(context.payroll.monthlyPayroll(),24);
state.hired=[];
assert.equal(context.payroll.monthlyPayroll(),0);
assert.match(source,/state\.assets=roundMoney\(state\.assets\+revenue-cost-salaryPaid/);
assert.match(source,/state\.staff\[w\.id\]=state\.staff\[w\.id\]\|\|\{level:1,xp:0\}/);
console.log('Hiring stays half-cost while salary rises with ability; firing removes future salary.');
