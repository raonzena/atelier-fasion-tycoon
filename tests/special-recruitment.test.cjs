const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const source=fs.readFileSync(path.join(__dirname,'../dist/client/game.js'),'utf8');
for(const sprite of ['ruby','flora','star','elli','theo']){
  assert.match(source,new RegExp("sprite:'cat-special-"+sprite+"'"));
  assert(fs.statSync(path.join(__dirname,'../dist/client/assets/cat-special-'+sprite+'.webp')).size>1000);
}
const start=source.indexOf('  const SPECIAL_APPEAR_CHANCE=');
const end=source.indexOf('  const showPager =',start);
assert(start>0&&end>start);
const workers=[{id:'regular',level:1},{id:'regular2',level:1},{id:'regular3',level:1},{id:'regular4',level:2},{id:'regular5',level:3},{id:'regular6',level:4},{id:'specialRuby',special:true},{id:'specialStar',special:true}];
const state={hired:[],officeLevel:1};
const context={workers,state};
vm.createContext(context);
vm.runInContext(source.slice(start,end)+'\nthis.drawSpecialCandidate=drawSpecialCandidate;this.drawRegularApplicants=drawRegularApplicants;',context);
const applicants=context.drawRegularApplicants(()=>0,5);
assert.equal(applicants.length,5);
assert(applicants.slice(0,3).every(w=>w.level===1));
assert(applicants.every(w=>!w.special));
state.hired=['regular2'];
assert(context.drawRegularApplicants(()=>.9,5).every(w=>w.id!=='regular2'));
state.hired=[];
assert.equal(context.drawSpecialCandidate(()=>.03),null);
let rolls=[.01,.8];
assert.equal(context.drawSpecialCandidate(()=>rolls.shift()).id,'specialStar');
state.hired=['specialStar'];
rolls=[.01,.8];
assert.equal(context.drawSpecialCandidate(()=>rolls.shift()).id,'specialRuby');
state.hired=['specialStar','specialRuby'];
assert.equal(context.drawSpecialCandidate(()=>0),null);
assert.match(source,/if\(newVisit\)\{featuredSpecial=drawSpecialCandidate\(\);regularApplicants=drawRegularApplicants/);
assert.match(source,/if\(featuredSpecial\)roster\.unshift\(featuredSpecial\)/);
assert.match(source,/showHire\(0,true\)/);
assert.match(source,/refreshApplicants/);
console.log('Five random applicants prioritize available hires; rare special staff lead the visit.');
